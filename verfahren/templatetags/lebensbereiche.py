def anzeigename(name: str) -> str:
    """Der Name zum Anzeigen: übersetzt, wenn er aus dem Erstbestand stammt, sonst unverändert."""
    return gettext(name) if name in ERSTBESTAND_NAMEN else name


def anzeigepfad(kategorie, ebenen: int = 3) -> str:
    """Wie `Kategorie.pfad_kurz`, mit den angezeigten Namen: die letzten `ebenen` Stufen bis zur Wurzel.
    Läuft dieselbe Elternkette wie das Modell (vorgeladen über select_related, Befund #39)."""
    teile, knoten = [], kategorie
    while knoten is not None:
        teile.append(anzeigename(knoten.name))
        knoten = knoten.eltern
    return " › ".join(list(reversed(teile))[-ebenen:])


@register.filter
def lb_name(kategorie) -> str:
    """{{ k|lb_name }} — der Name eines Lebensbereichs in der Sprache der Seite."""
    return anzeigename(getattr(kategorie, "name", "") or "")


@register.filter
def lb_pfad_kurz(kategorie) -> str:
    """{{ k|lb_pfad_kurz }} — der kurze Pfad (drei Ebenen) in der Sprache der Seite."""
    return anzeigepfad(kategorie)
